/**
 * Cantidad exacta de palabras de la lista. Con `WORDLIST_COUNT` palabras,
 * cada palabra de la frase aporta log2(WORDLIST_COUNT) bits: 256 → 8 bits.
 */
export const WORDLIST_COUNT = RECOVERY_WORDLIST.length;

const WORDLIST_SET: ReadonlySet<string> = new Set(RECOVERY_WORDLIST);

/**
 * Indica si `word` pertenece a la wordlist (comparación exacta, sensible
 * a mayúsculas: normalizar con `.toLowerCase()` antes de llamar si hace falta).
 */
export function isWordInList(word: string): boolean {
  return WORDLIST_SET.has(word);
}
